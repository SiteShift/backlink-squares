const assert = require('node:assert/strict')
const fs = require('node:fs')
const vm = require('node:vm')
const ts = require('typescript')
const exportsObject = {}
vm.runInNewContext(ts.transpileModule(fs.readFileSync('lib/tools/engine.ts','utf8'), { compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2022 } }).outputText, { exports: exportsObject, URL, console })
const { parseCSV, exportCSV, velocity, gap, anchors, gsc, pagerank, disavow, publicURL } = exportsObject
const plain = value => JSON.parse(JSON.stringify(value))
assert.deepEqual(plain(parseCSV('\uFEFFSite,Links\r\n"a,b",2\r\n"two\nlines",3')), [['Site','Links'],['a,b','2'],['two\nlines','3']])
assert.throws(() => parseCSV('"unfinished'))
assert.ok(exportCSV([['=SUM(A1:A2)']]).startsWith('"\''))
assert.equal(exportCSV([['-2']]), '"-2"')
const v = velocity('month,new_links,lost_links\n2026-02,5,8\n2026-01,10,2')
assert.deepEqual(plain(v.rows), [['2026-01','10','2','8','8'],['2026-02','5','8','-3','5']])
assert.throws(() => velocity('month,new_links,lost_links\n2026-01,2,0\n2026-01,3,0'))
assert.throws(() => velocity('month,new_links,lost_links\n2026-01,,0'))
assert.throws(() => velocity('month,new_links,lost_links\n2026-13,2,0'))
assert.deepEqual(plain(gap('https://www.example.com/a','example.com\nother.example.com\nexample.org').rows.map(r=>r[0])),['example.org','other.example.com'])
assert.equal(anchors('Acme\nAcme\nproject management','Acme','project management').rows[0][3], '66.7%')
assert.equal(gsc('Site,Linking pages\nexample.com,10\nexample.com,8\nexample.org,10').rows.length, 2)
assert.equal(gsc('Site,Linking pages\nexample.com,0').rows[0][2], '0%')
assert.throws(() => gsc('Target page,Links\nhttps://example.com,2'))
const rank = pagerank('A -> B\nA -> C\nB -> C\nC -> A', .85)
assert.ok(Math.abs(rank.rows.reduce((n,r)=>n+Number(r[1]),0)-1)<1e-6)
assert.ok(Math.abs(Number(rank.rows.find(r=>r[0]==='A')[1])-.38778971)<1e-6)
assert.equal(pagerank('A -> B', 0).rows[0][1], '.5'.replace('.5','0.50000000'))
assert.throws(()=>pagerank('A -> B', 1))
assert.equal(disavow('domain:example.com\ndomain:example.com').text, 'domain:example.com')
assert.throws(()=>disavow('domain:example.com/path'))
assert.throws(()=>publicURL('javascript:alert(1)'))
console.log('Tool regression checks passed: CSV quoting, safe export, velocity, gaps, anchors, GSC, PageRank and disavow validation.')
const roiSource = fs.readFileSync('app/tools/roi-calculator/page.tsx', 'utf8')
const roiBody = roiSource.split('const calculations = useMemo(() => {')[1].split('}, [monthlyBudget')[0]
const calculateROI = new Function('monthlyBudget','costPerLink','currentTraffic','conversionRate','orderValue','trafficIncreasePerLink',roiBody)
const zeroGrowth = calculateROI(100,100,1000,2,50,0)
assert.equal(zeroGrowth.additionalRevenue,0)
assert.equal(zeroGrowth.roi,-100)
assert.equal(zeroGrowth.breakEvenMonths,Infinity)
const growth = calculateROI(100,100,1000,2,50,1)
const annualGain = Array.from({length:12},(_,i)=>(1000 * 1.01 ** (i+1)-1000)*.02*50).reduce((a,b)=>a+b,0)
assert.ok(Math.abs(growth.additionalRevenue-annualGain)<1e-8)
console.log('ROI regression checks passed: annual revenue sums monthly gains and zero growth cannot break even.')
